export interface Salon {
  id: string;
  name: { en: string; ar: string };
  description: { en: string; ar: string };
  logo: string;
  cover: string;
  gallery: string[];
  rating: number;
  reviewsCount: number;
  location: { en: string; ar: string };
  neighborhood: string;
  phone: string;
  whatsapp: string;
  instagram: string;
  priceRange: '$$' | '$$$' | '$$$$';
  isLuxury: boolean;
  hasHomeService: boolean;
  services: Service[];
  staff: Staff[];
  workingHours: WorkingHours[];
  category: string;
  tags: string[];
  offers: string[];
}

export interface Service {
  id: string;
  name: { en: string; ar: string };
  price: number;
  duration: number;
  category: string;
}

export interface Staff {
  id: string;
  name: string;
  role: { en: string; ar: string };
  photo: string;
  rating: number;
  specialty: string;
}

export interface WorkingHours {
  day: string;
  open: string;
  close: string;
  isOpen: boolean;
}

export interface Offer {
  id: string;
  title: { en: string; ar: string };
  description: { en: string; ar: string };
  originalPrice: number;
  discountedPrice: number;
  discount: number;
  expiresAt: string;
  image: string;
  salonId: string;
  salonName: string;
}

export interface Category {
  id: string;
  name: { en: string; ar: string };
  icon: string;
  color: string;
  gradient: string;
  count: number;
}

export interface Review {
  id: string;
  customerName: string;
  customerAvatar: string;
  rating: number;
  comment: { en: string; ar: string };
  date: string;
  salonId: string;
  service: string;
}

export interface Package {
  id: string;
  name: { en: string; ar: string };
  description: { en: string; ar: string };
  services: string[];
  originalPrice: number;
  price: number;
  image: string;
  duration: number;
}

export interface BlogPost {
  id: string;
  title: { en: string; ar: string };
  excerpt: { en: string; ar: string };
  image: string;
  category: string;
  date: string;
  readTime: number;
}

