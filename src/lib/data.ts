export const getSalonById = (id: string): Salon | undefined => {
  return salons.find(salon => salon.id === id);
};

export const getOfferById = (id: string): Offer | undefined => {
  return offers.find(offer => offer.id === id);
};

export const getSalonsByCategory = (category: string): Salon[] => {
  return salons.filter(salon => salon.category === category);
};

export const getFeaturedSalons = (): Salon[] => {
  return salons.filter(s => s.rating >= 4.7).slice(0, 6);
};

export const getLuxurySalons = (): Salon[] => {
  return salons.filter(s => s.isLuxury).slice(0, 6);
};
